#!/usr/bin/env node
/**
 * One-off migration: exports every Firestore document of the old Firebase
 * project and writes an SQL file for Supabase's `public.documents` table.
 *
 *   FIREBASE_API_KEY=... node scripts/export-firestore.mjs
 *
 * Output (git-ignored, contains private data):
 *   migration/firestore-export.json   raw export
 *   migration/seed.sql                run in Supabase SQL Editor
 *   migration/files.json              Firebase Storage URLs still referenced
 *
 * It signs in anonymously, which the old Firestore rules allowed full read for.
 */
import { mkdir, writeFile } from "node:fs/promises";

const PROJECT = "my-cockpit-vu7m6";
const API_KEY = process.env.FIREBASE_API_KEY;
if (!API_KEY) {
  console.error("Set FIREBASE_API_KEY (the web apiKey of the Firebase project).");
  process.exit(1);
}

const COLLECTIONS = [
  "api_tokens", "app_config", "blog_posts", "clients", "files", "folders", "habits",
  "ideas", "invoices", "legal_files", "legal_info", "numbered_links", "products",
  "projects", "public_tools", "snippets", "subscriptions", "support_tickets", "tasks",
  "telegram_channels", "tools", "transactions",
];
const SUBCOLLECTIONS = { support_tickets: ["messages"] };

const BASE = `https://firestore.googleapis.com/v1/projects/${PROJECT}/databases/(default)/documents`;

async function signInAnonymously() {
  const res = await fetch(`https://identitytoolkit.googleapis.com/v1/accounts:signUp?key=${API_KEY}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ returnSecureToken: true }),
  });
  const body = await res.json();
  if (!res.ok) throw new Error(`Anonymous sign-in failed: ${JSON.stringify(body)}`);
  return body.idToken;
}

/** Firestore REST value -> plain JSON (timestamps become {"__ts": ISO}). */
function fromValue(v) {
  if ("nullValue" in v) return null;
  if ("booleanValue" in v) return v.booleanValue;
  if ("integerValue" in v) return Number(v.integerValue);
  if ("doubleValue" in v) return Number(v.doubleValue);
  if ("stringValue" in v) return v.stringValue;
  if ("timestampValue" in v) return { __ts: new Date(v.timestampValue).toISOString() };
  if ("referenceValue" in v) return v.referenceValue.split("/documents/")[1] ?? v.referenceValue;
  if ("geoPointValue" in v) return v.geoPointValue;
  if ("bytesValue" in v) return v.bytesValue;
  if ("arrayValue" in v) return (v.arrayValue.values ?? []).map(fromValue);
  if ("mapValue" in v) return fromFields(v.mapValue.fields ?? {});
  throw new Error(`Unknown Firestore value: ${JSON.stringify(v)}`);
}
function fromFields(fields) {
  return Object.fromEntries(Object.entries(fields).map(([k, v]) => [k, fromValue(v)]));
}

async function listCollection(token, path) {
  const docs = [];
  let pageToken = "";
  do {
    const url = `${BASE}/${path}?pageSize=300${pageToken ? `&pageToken=${encodeURIComponent(pageToken)}` : ""}`;
    const res = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
    const body = await res.json();
    if (!res.ok) throw new Error(`List ${path} failed: ${JSON.stringify(body.error ?? body)}`);
    for (const d of body.documents ?? []) {
      docs.push({
        collection: path,
        id: d.name.split("/").pop(),
        data: fromFields(d.fields ?? {}),
        created_at: d.createTime,
        updated_at: d.updateTime,
      });
    }
    pageToken = body.nextPageToken ?? "";
  } while (pageToken);
  return docs;
}

const sqlText = (s) => `'${String(s).replace(/'/g, "''")}'`;

async function main() {
  const token = await signInAnonymously();
  const all = [];
  for (const c of COLLECTIONS) {
    const docs = await listCollection(token, c);
    console.log(`${c}: ${docs.length}`);
    all.push(...docs);
    for (const sub of SUBCOLLECTIONS[c] ?? []) {
      let n = 0;
      for (const d of docs) {
        const children = await listCollection(token, `${c}/${d.id}/${sub}`);
        n += children.length;
        all.push(...children);
      }
      console.log(`  ${c}/*/${sub}: ${n}`);
    }
  }

  const files = new Set();
  JSON.stringify(all, (_k, v) => {
    if (typeof v === "string" && v.includes("firebasestorage.googleapis.com")) files.add(v);
    return v;
  });

  const values = all.map((d) =>
    `(${sqlText(d.collection)}, ${sqlText(d.id)}, ${sqlText(JSON.stringify(d.data))}::jsonb, ${sqlText(d.created_at)}, ${sqlText(d.updated_at)})`
  );
  const sql = [
    "-- Generated by scripts/export-firestore.mjs. Contains private data: do not commit.",
    "begin;",
    ...chunk(values, 200).map((rows) =>
      "insert into public.documents (collection, id, data, created_at, updated_at) values\n" +
      rows.join(",\n") +
      "\non conflict (collection, id) do update set data = excluded.data, created_at = excluded.created_at, updated_at = excluded.updated_at;"
    ),
    "commit;",
  ].join("\n");

  await mkdir("migration", { recursive: true });
  await writeFile("migration/firestore-export.json", JSON.stringify(all, null, 2));
  await writeFile("migration/seed.sql", sql + "\n");
  await writeFile("migration/files.json", JSON.stringify([...files], null, 2));
  console.log(`\n${all.length} documents, ${files.size} stored file URLs -> migration/`);
}

function chunk(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}

main().catch((e) => { console.error(e); process.exit(1); });
